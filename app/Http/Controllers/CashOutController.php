     * Store a newly created resource in storage.
     *
     * @param  \Illuminate\Http\Request  $request
     * @return \Illuminate\Http\Response
     */
    public function storeCashOut(Request $request)
    {
        $post = new TCashout;
        $post->Cashout_date = $request->Cashout_date;
        $post->Cashout_no = $request->Cashout_no;
        $post->Account = $request->Account;
        $post->Cashout_note = $request->Cashout_note;
        $post->Cashout_amount = $request->Cashout_amount;
        $post->save();
        return redirect('CashOut')->with('status', 'Cash Out Form Data Has Been inserted');
    }

